"""Writes src/app/certs.h: the root certificates the display trusts for https:// servers.

A short list of the roots behind most hosts (Let's Encrypt, Google, DigiCert, Amazon, Sectigo), taken from
the Mozilla bundle that pip ships. Run again to refresh:  python certs/make_certs.py
"""
import pathlib
import re

from pip._vendor import certifi

WANTED = [
    "ISRG Root X1",
    "ISRG Root X2",
    "GTS Root R1",
    "GTS Root R4",
    "DigiCert Global Root CA",
    "DigiCert Global Root G2",
    "Amazon Root CA 1",
    "USERTrust RSA Certification Authority",
]

bundle = pathlib.Path(certifi.where()).read_text(encoding="ascii")
found = {}
for label, pem in re.findall(r"# Label: \"([^\"]+)\"\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)", bundle, re.S):
    if label in WANTED and label not in found:
        found[label] = pem
missing = [name for name in WANTED if name not in found]
if missing:
    raise SystemExit(f"Not in the bundle: {missing}")

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "app" / "certs.h"
lines = [
    "// Generated by certs/make_certs.py from the Mozilla CA bundle. Do not edit by hand.",
    "#pragma once",
    "",
    "static const char WB_ROOT_CERTS[] =",
]
for name in WANTED:
    lines.append(f"    // {name}")
    for line in found[name].splitlines():
        lines.append('    "' + line + '\\n"')
lines[-1] += ";"
out.write_text("\n".join(lines) + "\n", encoding="ascii")
print(f"Wrote {len(WANTED)} roots to {out}")
